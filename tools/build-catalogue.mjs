// Lichess CC0 openings to a position keyed name map. Author time only: run it when the source data changes and commit
// the output. It never runs in the browser; the map is a lazily loaded chunk (src/openings/catalogue.js).
//
//   node tools/build-catalogue.mjs <dir with a.tsv ... e.tsv>
//
// Get the TSVs from https://github.com/lichess-org/chess-openings (CC0 1.0). Keyed by position (Chess#positionKey4),
// not by move sequence, so a transposition gets the same name however it was reached. The first name wins: the TSVs
// list a general name before its own sub variations.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Chess } from '../src/rules.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-catalogue.mjs <dir with a.tsv ... e.tsv>'); process.exit(2); }

const map = {};
let rows = 0, failed = 0;
for (const letter of ['a', 'b', 'c', 'd', 'e']) {
  const tsv = readFileSync(join(dir, `${letter}.tsv`), 'utf8');
  for (const line of tsv.split('\n').slice(1)) {
    if (!line.trim()) continue;
    const [eco, name, pgn] = line.split('\t');
    if (!pgn) continue;
    rows++;
    const game = new Chess();
    let ok = true;
    for (const token of pgn.split(/\s+/)) {
      if (!token || /^\d+\.+$/.test(token)) continue;
      if (!game.playSan(token.replace(/^\d+\.+/, ''))) { ok = false; break; }
    }
    if (!ok) { failed++; console.warn(`  skipped ${eco} ${name}: ${pgn}`); continue; }
    const k = game.positionKey4();
    if (!(k in map)) map[k] = [eco, name];
  }
}

const body = `// GENERATED by tools/build-catalogue.mjs, do not edit.
//
// Position key (placement, turn, castling, en passant) to [ECO, name], from lichess-org/chess-openings (CC0 1.0,
// public domain). ${Object.keys(map).length} positions. Loaded lazily by src/openings/catalogue.js.

export const MAP = ${JSON.stringify(map)};
`;
writeFileSync(join(ROOT, 'src/openings/catalogue-data.js'), body);
console.log(`${rows} rows, ${failed} failed, ${Object.keys(map).length} positions, ${(body.length / 1024).toFixed(0)} KB`);
